#!/bin/zsh
# Metal precompile must tell "the toolchain is not there yet" from "the compiler
# ran and failed". The first skips one build; the second switches precompile off
# for the rest of the run. The probe at startup used to make the second decision
# on the strength of the first, so one missing xcrun at launch left every engine
# compiling its shaders at first load.
#
#   ./scripts/test-metal-precompile.sh
#
# Sources build-engines.sh for its real precompile_merged_metallib, then shadows
# resolve_metal_toolchain so availability and compiler exit status are ours.
# Exit 0 when every expectation holds, 1 otherwise.
set -u

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
source "$ROOT_DIR/scripts/build-engines.sh"
# build-engines.sh sets -e; the assertions below probe failures on purpose.
set +e

pass=0
fail=0
check() {
    local want="$1" got="$2" what="$3"
    if [ "$want" = "$got" ]; then
        pass=$((pass + 1))
        echo "  ok   $what"
    else
        fail=$((fail + 1))
        echo "  FAIL $what — want '$want', got '$got'"
    fi
}

# A scratch engine root with the layout precompile_merged_metallib expects.
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

MERGED="build-static/ggml/src/ggml-metal/autogenerated/ggml-metal-embed.metal"
mkdir -p "${MERGED:h}" build-static/bin fakebin
: > "$MERGED"

# Compiler stand-ins: metal-ok writes its -o argument, metal-bad exits 1 without.
cat > fakebin/metal-ok <<'EOS'
#!/bin/sh
while [ $# -gt 0 ]; do
    if [ "$1" = "-o" ]; then shift; : > "$1"; exit 0; fi
    shift
done
exit 1
EOS
cat > fakebin/metallib <<'EOS'
#!/bin/sh
while [ $# -gt 0 ]; do
    if [ "$1" = "-o" ]; then shift; : > "$1"; exit 0; fi
    shift
done
exit 1
EOS
printf '#!/bin/sh\nexit 1\n' > fakebin/metal-bad
chmod +x fakebin/metal-ok fakebin/metal-bad fakebin/metallib

# Availability is ours. resolve is counted so "no attempt" can be asserted too.
toolchain_present=1
fake_metal="$WORK/fakebin/metal-ok"
resolve_calls=0
resolve_metal_toolchain() {
    resolve_calls=$((resolve_calls + 1))
    [ "$toolchain_present" = 1 ] || return 1
    METAL_COMPILER="$fake_metal"
    METALLIB_COMPILER="$WORK/fakebin/metallib"
    return 0
}

echo "metal precompile behaviour:"

# The case that was broken: unavailable at this instant, but not a compile failure.
toolchain_present=0
METAL_PRECOMPILE=1
precompile_merged_metallib "alpha" >/dev/null 2>&1
check 1 "$METAL_PRECOMPILE" "a missing toolchain leaves METAL_PRECOMPILE enabled"
check 1 "$resolve_calls" "a missing toolchain still went through resolve"
check 1 "$([ -f "$MERGED" ] && echo 1 || echo 0)" "the merged source is untouched"

# Still enabled means the next engine gets its own attempt.
toolchain_present=1
METAL_PRECOMPILE=1
resolve_calls=0
precompile_merged_metallib "beta" >/dev/null 2>&1
check 1 "$METAL_PRECOMPILE" "the next engine is attempted after a missing toolchain"
check 1 "$([ -f build-static/bin/default.metallib ] && echo 1 || echo 0)" \
        "a working toolchain produces default.metallib"

# A compiler that runs and fails is the decision worth keeping.
rm -f build-static/bin/default.metallib
toolchain_present=1
fake_metal="$WORK/fakebin/metal-bad"
METAL_PRECOMPILE=1
precompile_merged_metallib "gamma" >/dev/null 2>&1
check 0 "$METAL_PRECOMPILE" "a compiler failure does switch METAL_PRECOMPILE off"
check 0 "$([ -f build-static/bin/default.metallib ] && echo 1 || echo 0)" \
        "a failed precompile leaves no partial default.metallib"

# Off means no further attempts: the failed compiler is not retried per engine.
fake_metal="$WORK/fakebin/metal-ok"
toolchain_present=1
resolve_calls=0
precompile_merged_metallib "delta" >/dev/null 2>&1
check 0 "$resolve_calls" "an already-disabled precompile makes no further attempt"

echo "$pass passed, $fail failed"
[ "$fail" = 0 ]